export type TranslationKey = keyof typeof translations.en;

interface I18nState {
  language: Language;
  setLanguage: (lang: Language) => Promise<void>;
  restoreLanguage: () => Promise<void>;
  t: (key: TranslationKey) => string;
}

export const useI18nStore = create<I18nState>((set, get) => ({
  language: 'en',
  setLanguage: async (lang: Language) => {
    set({ language: lang });
    try {
      await AppStorage.setItem(STORAGE_KEY, lang);
    } catch {
      // fallback
    }
  },
  restoreLanguage: async () => {
    try {
      const saved = (await AppStorage.getItem(STORAGE_KEY)) as Language | null;
      if (saved === 'en' || saved === 'te') {
        set({ language: saved });
      }
    } catch {
      // fallback
    }
  },
  t: (key: TranslationKey) => {
    const lang = get().language;
    return translations[lang]?.[key] || translations.en[key] || key;
  },
}));

export function useTranslation() {
  const { language, setLanguage, restoreLanguage, t } = useI18nStore();
  return { language, setLanguage, restoreLanguage, t };
}